"""Synthetic instance generator.

The generator is a deliverable, not a shortcut (PROJECT_BRIEF.md section 3).
It is fully deterministic: same seed in, byte-identical instance out. The
numbers we quote in the deck have to be reproducible on demand.

Phase 0 scope: 5 sections, 20 tasks, 7-day horizon, hardcoded traffic.
"""

from __future__ import annotations

import random
from datetime import date, datetime, timedelta

from src.generator.catalogue import CATALOGUE, ActivitySpec
from src.generator.sections import archetype_of, build_sections
from src.models import (
    CrewCapacity,
    DataProvenance,
    Department,
    PlanningInstance,
    Section,
    Severity,
    SourceKind,
    Task,
    TrafficWindow,
)

PROVENANCE = (
    "SYNTHETIC. Generated by src/generator/synthetic.py. No Indian Railways "
    "operational data was used. Real TMS/SMMS/TDMS/COA feeds attach at the "
    "adapter layer (src/adapters). See ASSUMPTIONS.md."
)

# Day-of-week traffic multipliers, 0 = Monday. Sunday and Saturday run lighter
# passenger services. HAND-CHOSEN, see ASSUMPTIONS.md (A-04).
DOW_MULTIPLIER: tuple[float, ...] = (1.00, 1.00, 1.00, 1.00, 1.05, 0.90, 0.75)

# Freight is flagged on night hours of mixed-traffic sections, where goods
# paths are concentrated. See ASSUMPTIONS.md (A-04).
GOODS_HOURS = range(22, 24)
GOODS_HOURS_EARLY = range(0, 5)

# Crews a department can field per day on a division of this size.
# PROVISIONAL, see ASSUMPTIONS.md (A-06).
CREWS_PER_DEPARTMENT: dict[Department, tuple[int, int]] = {
    Department.ENGG: (2, 3),
    Department.TRD: (1, 2),
    Department.SNT: (1, 2),
}

# How the backlog is distributed. Roughly a quarter of pending work is already
# past its mandated date, which is what makes coordination urgent.
# See ASSUMPTIONS.md (A-07).
OVERDUE_FRACTION = 0.25
DUE_IN_HORIZON_FRACTION = 0.40


def _pick_severity(rng: random.Random, days_past_due: int) -> Severity:
    """Severity correlates with lateness, with noise.

    The correlation is deliberate: the Phase 3 criticality model needs real
    signal to learn, and in practice a defect left unattended degrades.
    """
    if days_past_due > 30:
        weights = [1, 2, 4, 6, 5]
    elif days_past_due > 0:
        weights = [2, 4, 5, 4, 2]
    else:
        weights = [5, 6, 4, 2, 1]
    return Severity(rng.choices([1, 2, 3, 4, 5], weights=weights, k=1)[0])


def _make_task(
    rng: random.Random,
    idx: int,
    section: Section,
    spec: ActivitySpec,
    horizon_start: date,
    horizon_days: int,
) -> Task:
    """Place one task on the due-date timeline.

    We choose where the task sits relative to its due date first, then work
    backwards to last_done_date. That way the backlog mix is controlled
    rather than emergent.
    """
    roll = rng.random()
    if roll < OVERDUE_FRACTION:
        # Already past due when the horizon opens.
        days_to_due = -rng.randint(1, 45)
    elif roll < OVERDUE_FRACTION + DUE_IN_HORIZON_FRACTION:
        # Falls due inside the planning window: must be scheduled.
        days_to_due = rng.randint(0, horizon_days)
    else:
        # Comfortably ahead: the optimiser may defer it.
        days_to_due = rng.randint(horizon_days + 1, horizon_days + 60)

    due_date = horizon_start + timedelta(days=days_to_due)
    last_done_date = due_date - timedelta(days=spec.interval_days)
    lo, hi = spec.duration_minutes_range
    crew_lo, crew_hi = spec.crew_range

    return Task(
        id=f"T{idx:03d}",
        department=spec.department,
        section_id=section.id,
        activity_type=spec.activity_type,
        # Round to 15-minute granularity: blocks are requested in quarter
        # hours, and it keeps the CP-SAT time grid small. ASSUMPTIONS.md (A-03).
        duration_minutes=15 * rng.randint(lo // 15, hi // 15),
        crew_required=rng.randint(crew_lo, crew_hi),
        last_done_date=last_done_date,
        interval_days=spec.interval_days,
        due_date=due_date,
        defect_severity=_pick_severity(rng, max(0, -days_to_due)),
        is_overdue=due_date < horizon_start,
        co_locatable=spec.co_locatable,
    )


def _build_traffic(
    sections: list[Section], horizon_start: date, horizon_days: int
) -> list[TrafficWindow]:
    """Materialise the per-section, per-day, per-hour traffic view.

    Section.traffic_density_profile is the baseline weekday shape; this
    applies the day-of-week multiplier to produce what the optimiser costs
    against.
    """
    windows: list[TrafficWindow] = []
    for section in sections:
        try:
            archetype = archetype_of(section.id)
        except KeyError:
            # A real, timetable-derived section. We have no freight data for
            # it: public passenger timetables do not carry goods paths, and
            # guessing them would be inventing traffic. Leave unflagged.
            archetype = None
        for day_offset in range(horizon_days):
            day = horizon_start + timedelta(days=day_offset)
            dow = day.weekday()
            multiplier = DOW_MULTIPLIER[dow]
            for hour in range(24):
                base = section.traffic_density_profile[hour]
                is_goods = archetype == "mixed_trunk" and (
                    hour in GOODS_HOURS or hour in GOODS_HOURS_EARLY
                )
                windows.append(
                    TrafficWindow(
                        section_id=section.id,
                        day=day,
                        hour_of_day=hour,
                        day_of_week=dow,
                        trains_per_hour=round(base * multiplier, 2),
                        is_goods_forecast=is_goods,
                    )
                )
    return windows


def _build_crew_capacity(
    rng: random.Random, horizon_start: date, horizon_days: int
) -> list[CrewCapacity]:
    capacity: list[CrewCapacity] = []
    for day_offset in range(horizon_days):
        day = horizon_start + timedelta(days=day_offset)
        for dept, (lo, hi) in CREWS_PER_DEPARTMENT.items():
            crews = rng.randint(lo, hi)
            # Sunday: reduced establishment.
            if day.weekday() == 6:
                crews = max(1, crews - 1)
            capacity.append(
                CrewCapacity(department=dept, date=day, available_crews=crews)
            )
    return capacity


def generate_tasks(
    rng: random.Random,
    sections: list[Section],
    n_tasks: int,
    horizon_start: date,
    horizon_days: int,
) -> list[Task]:
    """Generate a synthetic maintenance backlog against any section list.

    Split out from generate_instance so the same backlog logic can be laid
    over real, timetable-derived sections. See src/adapters/hybrid.py.
    """
    tasks: list[Task] = []
    for idx in range(1, n_tasks + 1):
        section = rng.choice(sections)
        spec = rng.choice(CATALOGUE)
        tasks.append(_make_task(rng, idx, section, spec, horizon_start, horizon_days))
    return tasks


def build_traffic(
    sections: list[Section], horizon_start: date, horizon_days: int
) -> list[TrafficWindow]:
    """Public wrapper: expand section profiles into per-day traffic windows."""
    return _build_traffic(sections, horizon_start, horizon_days)


def build_crew_capacity(
    rng: random.Random, horizon_start: date, horizon_days: int
) -> list[CrewCapacity]:
    """Public wrapper for crew capacity generation."""
    return _build_crew_capacity(rng, horizon_start, horizon_days)


def generate_instance(
    seed: int = 42,
    n_tasks: int = 20,
    horizon_start: date = date(2026, 3, 2),  # a Monday
    horizon_days: int = 7,
    n_sections: int | None = 5,
) -> PlanningInstance:
    """Build one deterministic synthetic planning instance."""
    rng = random.Random(seed)

    sections = build_sections()
    if n_sections is not None:
        sections = sections[:n_sections]

    tasks = generate_tasks(rng, sections, n_tasks, horizon_start, horizon_days)

    instance = PlanningInstance(
        instance_id=f"phase0-s{seed}-{n_sections}sec-{n_tasks}task-{horizon_days}d",
        generated_at=datetime(2026, 1, 1, 0, 0, 0),  # fixed: keeps output byte-stable
        seed=seed,
        sources=DataProvenance(
            sections=SourceKind.SYNTHETIC,
            tasks=SourceKind.SYNTHETIC,
            traffic=SourceKind.SYNTHETIC,
            crew_capacity=SourceKind.SYNTHETIC,
            notes="Fully synthetic Phase 0 instance; no external data used.",
        ),
        provenance=PROVENANCE,
        horizon_start=horizon_start,
        horizon_days=horizon_days,
        sections=sections,
        tasks=tasks,
        traffic=_build_traffic(sections, horizon_start, horizon_days),
        crew_capacity=_build_crew_capacity(rng, horizon_start, horizon_days),
    )
    instance.validate_referential_integrity()
    return instance
